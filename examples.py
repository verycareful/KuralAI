# Quick accessor
def get_example_by_id(example_id: str) -> dict | None:
    """Get an example by its ID."""
    for ex in EXAMPLES:
        if ex["id"] == example_id:
            return ex
    return None


def get_all_titles() -> list[dict]:
    """Return a list of {id, title, title_en, description} for all examples."""
    return [
        {"id": ex["id"], "title": ex["title"], "title_en": ex["title_en"], "description": ex["description"]}
        for ex in EXAMPLES
    ]


